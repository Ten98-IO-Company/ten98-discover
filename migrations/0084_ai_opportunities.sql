CREATE TABLE ai_opportunity_preparation (
 id uuid PRIMARY KEY,
 workspace_id text NOT NULL,
 project_id text NOT NULL,
 user_id text NOT NULL REFERENCES "user"(id),
 request_id uuid NOT NULL,
 connection_id uuid NOT NULL,
 connection_revision integer NOT NULL CHECK(connection_revision>0),
 request_actor text NOT NULL CHECK(request_actor ~ '^[a-f0-9]{64}$'),
 key_fingerprint text NOT NULL CHECK(key_fingerprint ~ '^[a-f0-9]{64}$'),
 purpose text NOT NULL CHECK(purpose='ai-opportunities'),
 prompt_version text NOT NULL CHECK(prompt_version='retained-api-opportunities-v1'),
 schema_version integer NOT NULL CHECK(schema_version=1),
 method text NOT NULL CHECK(method='evidence-linked-opportunities-v1'),
 source_kind text NOT NULL CHECK(source_kind='api-model-answer'),
 input_hash text NOT NULL CHECK(input_hash ~ '^[a-f0-9]{64}$'),
 payload_hash text NOT NULL CHECK(payload_hash ~ '^[a-f0-9]{64}$'),
 schema_hash text NOT NULL CHECK(schema_hash ~ '^[a-f0-9]{64}$'),
 evidence_hash text NOT NULL CHECK(evidence_hash ~ '^[a-f0-9]{64}$'),
 business_input_hash text NOT NULL CHECK(business_input_hash ~ '^[a-f0-9]{64}$'),
 retention_revision integer NOT NULL CHECK(retention_revision>0),
 raw_days_at_preparation integer NOT NULL CHECK(raw_days_at_preparation BETWEEN 1 AND 3650),
 derived_days_at_preparation integer NOT NULL CHECK(derived_days_at_preparation BETWEEN 1 AND 3650),
 raw_anchor_at timestamptz NOT NULL,
 derived_anchor_at timestamptz NOT NULL,
 -- Source dependencies retain only IDs, hashes and original timestamps after payload expiry.
 dependencies jsonb NOT NULL CHECK(jsonb_typeof(dependencies)='array' AND jsonb_array_length(dependencies) BETWEEN 1 AND 1000 AND octet_length(dependencies::text)<=1048576),
 source_input jsonb CHECK(source_input IS NULL OR (jsonb_typeof(source_input)='object' AND octet_length(source_input::text)<=32768)),
 snapshot jsonb CHECK(snapshot IS NULL OR (jsonb_typeof(snapshot)='object' AND octet_length(snapshot::text)<=262144)),
 messages jsonb CHECK(messages IS NULL OR (jsonb_typeof(messages)='array' AND jsonb_array_length(messages)=2 AND octet_length(messages::text)<=262144)),
 route jsonb NOT NULL CHECK(jsonb_typeof(route)='object' AND octet_length(route::text)<=8192),
 raw_expired_at timestamptz,
 input_purged_at timestamptz,
 unavailable_reason text CHECK(unavailable_reason IN('source_expired','source_changed','source_deleted','authority_changed','input_expired')),
 created_at timestamptz NOT NULL,
 expires_at timestamptz NOT NULL,
 UNIQUE(project_id,request_id),
 UNIQUE(id,workspace_id,project_id,user_id),
 FOREIGN KEY(project_id,workspace_id) REFERENCES project(id,workspace_id) ON DELETE CASCADE,
 FOREIGN KEY(connection_id,workspace_id) REFERENCES provider_connection(id,workspace_id),
 CHECK(expires_at=created_at+interval '5 minutes'),
 CHECK(raw_anchor_at<=created_at AND derived_anchor_at<=created_at),
 CHECK((source_input IS NOT NULL AND snapshot IS NOT NULL AND messages IS NOT NULL AND input_purged_at IS NULL)
    OR (source_input IS NULL AND snapshot IS NULL AND messages IS NULL AND input_purged_at IS NOT NULL)),
 CHECK(input_purged_at IS NULL OR raw_expired_at IS NOT NULL),
 CHECK((raw_expired_at IS NULL)=(unavailable_reason IS NULL))
);
CREATE INDEX ai_opportunity_preparation_retention_idx ON ai_opportunity_preparation(project_id,created_at,id) WHERE input_purged_at IS NULL;
CREATE INDEX ai_opportunity_preparation_business_idx ON ai_opportunity_preparation(project_id,business_input_hash);

CREATE TABLE ai_opportunity_run (
 id uuid PRIMARY KEY,
 preparation_id uuid NOT NULL UNIQUE,
 workspace_id text NOT NULL,
 project_id text NOT NULL,
 user_id text NOT NULL,
 request_id uuid NOT NULL,
 status text NOT NULL CHECK(status IN('queued','running','completed','failed','uncertain','cancelled')),
 lease_owner uuid,
 lease_expires_at timestamptz,
 generation_id text CHECK(generation_id IS NULL OR generation_id ~ '^gen-[0-9A-Za-z-]{1,124}$'),
 dispatched_at timestamptz,
 completed_at timestamptz,
 raw_result text CHECK(raw_result IS NULL OR octet_length(raw_result)<=65536),
 proposal jsonb CHECK(proposal IS NULL OR (jsonb_typeof(proposal)='object' AND octet_length(proposal::text)<=131072)),
 result_hash text CHECK(result_hash IS NULL OR result_hash ~ '^[a-f0-9]{64}$'),
 prompt_tokens integer CHECK(prompt_tokens BETWEEN 0 AND 2000000),
 completion_tokens integer CHECK(completion_tokens BETWEEN 0 AND 2000000),
 request_evidence jsonb CHECK(request_evidence IS NULL OR (jsonb_typeof(request_evidence)='object' AND octet_length(request_evidence::text)<=16384)),
 diagnostic text CHECK(diagnostic IS NULL OR length(diagnostic)<=1000),
 result_purged_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 UNIQUE(project_id,request_id),
 FOREIGN KEY(project_id,workspace_id) REFERENCES project(id,workspace_id) ON DELETE CASCADE,
 FOREIGN KEY(preparation_id,workspace_id,project_id,user_id) REFERENCES ai_opportunity_preparation(id,workspace_id,project_id,user_id),
 FOREIGN KEY(id,workspace_id) REFERENCES provider_request(id,workspace_id),
 CHECK((lease_owner IS NULL)=(lease_expires_at IS NULL)),
 CHECK(status<>'queued' OR dispatched_at IS NULL),
 CHECK(status<>'running' OR (dispatched_at IS NOT NULL AND lease_owner IS NOT NULL)),
 CHECK(status<>'cancelled' OR dispatched_at IS NULL),
 CHECK(status NOT IN('completed','failed','uncertain') OR dispatched_at IS NOT NULL),
 CHECK((status IN('queued','running'))=(completed_at IS NULL)),
 CHECK(status<>'completed' OR proposal IS NOT NULL OR result_purged_at IS NOT NULL),
 CHECK((proposal IS NULL)=(result_hash IS NULL)),
 CHECK(proposal IS NULL OR status='completed'),
 CHECK(result_purged_at IS NULL OR (raw_result IS NULL AND proposal IS NULL AND result_hash IS NULL)),
 CHECK(dispatched_at IS NULL OR dispatched_at>=created_at),
 CHECK(completed_at IS NULL OR completed_at>=created_at),
 CHECK(completed_at IS NULL OR dispatched_at IS NULL OR completed_at>=dispatched_at)
);
CREATE UNIQUE INDEX ai_opportunity_active_project_idx ON ai_opportunity_run(project_id) WHERE status IN('queued','running');
CREATE INDEX ai_opportunity_uncertain_project_idx ON ai_opportunity_run(project_id,preparation_id) WHERE status='uncertain';
CREATE INDEX ai_opportunity_history_idx ON ai_opportunity_run(project_id,created_at DESC,id DESC);
CREATE INDEX ai_opportunity_pending_idx ON ai_opportunity_run(status,lease_expires_at);
